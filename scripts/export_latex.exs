# CSV do Benchee → tabela LaTeX (booktabs).
#
#   elixir scripts/export_latex.exs results/pipeline.csv
#   elixir scripts/export_latex.exs results/pipeline.csv results/tables/pipeline.tex
#
# Colunas: n, estilo, mediana (µs), desvio relativo (%), memória mediana (KiB),
# razão vs. o mais rápido no mesmo n. Só stdlib.

defmodule ExportLatex do
  # {key, candidate header names, required?}
  @columns [
    {:name, ["Name"], true},
    {:input, ["Input"], true},
    {:median, ["Run Time Median", "Median"], true},
    {:average, ["Run Time Average", "Average"], false},
    {:std_dev, ["Run Time Standard Deviation", "Standard Deviation"], false},
    {:memory, ["Memory Usage Median", "Memory Usage Average", "Memory Usage"], false}
  ]

  @style_order ["recursive", "recursive_fused", "eager", "lazy"]

  def main([csv_path]), do: IO.puts(render(csv_path))

  def main([csv_path, out_path]) do
    File.mkdir_p!(Path.dirname(out_path))
    File.write!(out_path, render(csv_path))
    IO.puts("wrote #{out_path}")
  end

  def main(_) do
    IO.puts(:stderr, "usage: elixir scripts/export_latex.exs <benchee.csv> [out.tex]")
    System.halt(1)
  end

  defp render(csv_path) do
    [header | rows] =
      csv_path
      |> File.read!()
      |> String.split(~r/\r?\n/, trim: true)
      |> Enum.map(&parse_line/1)

    index =
      for {key, candidates, required?} <- @columns,
          into: %{},
          do: {key, find_column(header, candidates, required?)}

    records =
      rows
      |> Enum.map(&to_record(&1, index))
      |> Enum.sort_by(fn r -> {size_key(r.input), style_rank(r.name)} end)

    fastest =
      records
      |> Enum.group_by(& &1.input)
      |> Map.new(fn {input, group} -> {input, group |> Enum.map(& &1.median) |> Enum.min()} end)

    operation = Path.basename(csv_path, ".csv")

    body =
      records
      |> Enum.chunk_by(& &1.input)
      |> Enum.map_join("\n    \\midrule\n", fn group ->
        Enum.map_join(group, "\n", &row(&1, fastest[&1.input]))
      end)

    """
    % Generated by scripts/export_latex.exs from #{csv_path}
    \\begin{table}[t]
      \\centering
      \\caption{Operação \\texttt{#{escape(operation)}}: mediana do tempo, desvio-padrão relativo, memória alocada e razão em relação ao estilo mais rápido.}
      \\label{tab:#{operation}}
      \\begin{tabular}{rlrrrr}
        \\toprule
        $n$ & Estilo & Mediana ($\\mu$s) & DP (\\%) & Memória (KiB) & Razão \\\\
        \\midrule
    #{body}
        \\bottomrule
      \\end{tabular}
    \\end{table}
    """
  end

  defp to_record(row, index) do
    field = fn key -> (i = index[key]) && Enum.at(row, i) end
    median = to_float!(field.(:median), :median)

    %{
      name: field.(:name),
      input: field.(:input),
      median: median,
      average: to_float_or(field.(:average), median),
      std_dev: to_float_or(field.(:std_dev), 0.0),
      memory: to_float_or(field.(:memory), nil)
    }
  end

  defp row(r, fastest_median) do
    std_pct = if r.average > 0, do: 100 * r.std_dev / r.average, else: 0.0
    ratio = if fastest_median > 0, do: r.median / fastest_median, else: 1.0
    memory = if r.memory, do: number(r.memory / 1_024, 1), else: "--"

    cells = [
      String.replace(r.input, "_", "."),
      "\\texttt{#{escape(r.name)}}",
      number(r.median / 1_000, 2),
      number(std_pct, 1),
      memory,
      number(ratio, 2) <> "$\\times$"
    ]

    "    " <> Enum.join(cells, " & ") <> " \\\\"
  end

  defp find_column(header, candidates, required?) do
    downcased = Enum.map(header, &(&1 |> String.trim() |> String.downcase()))

    found =
      Enum.find_value(candidates, fn candidate ->
        Enum.find_index(downcased, &(&1 == String.downcase(candidate)))
      end)

    if is_nil(found) and required? do
      raise "column #{inspect(candidates)} not found. Available: #{inspect(header)}"
    end

    found
  end

  defp to_float!(value, field) do
    to_float_or(value, nil) || raise "invalid #{field} value: #{inspect(value)}"
  end

  defp to_float_or(nil, default), do: default

  defp to_float_or(value, default) do
    case Float.parse(String.trim(value)) do
      {number, _} -> number
      :error -> default
    end
  end

  defp size_key(input) do
    case Integer.parse(String.replace(input, ["_", ".", ","], "")) do
      {n, _} -> {0, n}
      :error -> {1, input}
    end
  end

  defp style_rank(name), do: Enum.find_index(@style_order, &(&1 == name)) || length(@style_order)

  # Brazilian Portuguese number format: comma as decimal separator.
  defp number(value, decimals) do
    value
    |> :erlang.float_to_binary(decimals: decimals)
    |> String.replace(".", "{,}")
  end

  defp escape(text), do: String.replace(text, "_", "\\_")

  # Minimal RFC 4180 line parser: quoted fields, embedded commas, doubled quotes.
  defp parse_line(line), do: parse_line(line, "", [], false)

  defp parse_line("", field, acc, _quoted), do: Enum.reverse([field | acc])

  defp parse_line(<<"\"\"", rest::binary>>, field, acc, true),
    do: parse_line(rest, field <> "\"", acc, true)

  defp parse_line(<<"\"", rest::binary>>, field, acc, quoted),
    do: parse_line(rest, field, acc, not quoted)

  defp parse_line(<<",", rest::binary>>, field, acc, false),
    do: parse_line(rest, "", [field | acc], false)

  defp parse_line(<<char::utf8, rest::binary>>, field, acc, quoted),
    do: parse_line(rest, field <> <<char::utf8>>, acc, quoted)
end

ExportLatex.main(System.argv())
